/**
 * Build the Kenney CC0 shell of the `/admin/3d` stockroom (floor, walls, rugs).
 * Downloads the kits, runs gltf-transform (Meshopt geometry + WebP textures),
 * writes content-hashed GLBs, the manifest and the TypeScript asset map.
 *
 * Run: node scripts/stockroom-3d-assets.mjs
 * Needs: curl, unzip, network access (npx fetches @gltf-transform/cli once).
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const GLTF_TRANSFORM = '@gltf-transform/cli@4.5.1';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'src/assets/3d/stockroom');
const tsOut = join(root, 'src/app/scene-engine/stockroom/stockroom-assets.ts');
const cacheDir = join(tmpdir(), 'lc-kenney');

const KITS = {
  'furniture-kit': {
    name: 'Furniture Kit',
    page: 'https://kenney.nl/assets/furniture-kit',
    zip: 'https://kenney.nl/media/pages/assets/furniture-kit/440e0608a4-1677580847/kenney_furniture-kit.zip',
    models: 'Models/GLTF format',
  },
  'mini-market': {
    name: 'Mini Market',
    page: 'https://kenney.nl/assets/mini-market',
    zip: 'https://kenney.nl/media/pages/assets/mini-market/463f38da51-1729865423/kenney_mini-market.zip',
    models: 'Models/GLB format',
  },
};

/** key → [kit, source file]. Keys become `STOCKROOM_ASSETS` fields. */
const MODELS = {
  rug: ['furniture-kit', 'rugRectangle.glb'],
  wall: ['furniture-kit', 'wall.glb'],
  wallWindow: ['furniture-kit', 'wallWindow.glb'],
  floor: ['mini-market', 'floor.glb'],
};

const OPTIMIZE_FLAGS = [
  '--compress', 'meshopt',
  '--texture-compress', 'webp',
  '--texture-size', '512',
  '--simplify', 'false',
  '--instance', 'false',
  '--palette', 'false',
  '--join', 'false',
  '--flatten', 'false',
];

function hash8(buf) {
  return createHash('sha256').update(buf).digest('hex').slice(0, 8);
}

function kitDir(id) {
  const kit = KITS[id];
  const dir = join(cacheDir, id);
  if (existsSync(join(dir, kit.models))) return dir;
  mkdirSync(dir, { recursive: true });
  const zip = join(cacheDir, `${id}.zip`);
  execFileSync('curl', ['-sSfL', '-o', zip, kit.zip], { stdio: 'inherit' });
  execFileSync('unzip', ['-oq', zip, '-d', dir], { stdio: 'inherit' });
  return dir;
}

function gltfTransform(args) {
  execFileSync('npx', ['--yes', GLTF_TRANSFORM, ...args], { stdio: ['ignore', 'ignore', 'inherit'] });
}

mkdirSync(outDir, { recursive: true });
for (const name of readdirSync(outDir)) {
  if (name.endsWith('.glb')) unlinkSync(join(outDir, name));
}

const work = join(cacheDir, 'work');
mkdirSync(work, { recursive: true });
const manifest = [];
const assetMap = {};

for (const [key, [kitId, file]] of Object.entries(MODELS)) {
  const src = join(kitDir(kitId), KITS[kitId].models, file);
  const raw = join(work, `${key}.raw.glb`);
  const packed = join(work, `${key}.glb`);
  gltfTransform(['copy', src, raw]);
  gltfTransform(['optimize', raw, packed, ...OPTIMIZE_FLAGS]);
  const buf = readFileSync(packed);
  const stem = file.replace(/\.glb$/, '');
  const name = `kenney-${stem}.${hash8(buf)}.glb`;
  writeFileSync(join(outDir, name), buf);
  assetMap[key] = `assets/3d/stockroom/${name}`;
  manifest.push({
    key,
    file: `assets/3d/stockroom/${name}`,
    bytes: buf.length,
    rawBytes: statSync(raw).size,
    source: `${KITS[kitId].name} / ${file}`,
    url: KITS[kitId].page,
    author: 'Kenney',
    license: 'CC0-1.0',
    compressed: 'meshopt+webp',
  });
}

writeFileSync(join(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

const lines = Object.entries(assetMap).map(([key, url]) => `  ${key}: '${url}',`);
writeFileSync(
  tsOut,
  [
    '/** Generated by `scripts/stockroom-3d-assets.mjs`. Hashed names — safe to cache forever. */',
    'export const STOCKROOM_ASSETS = {',
    ...lines,
    '} as const;',
    '',
    'export type StockroomAssetId = keyof typeof STOCKROOM_ASSETS;',
    '',
  ].join('\n'),
);

const total = manifest.reduce((n, m) => n + m.bytes, 0);
const rawTotal = manifest.reduce((n, m) => n + m.rawBytes, 0);
for (const m of manifest) console.log(`${m.file}  ${(m.bytes / 1024).toFixed(1)} KB  (raw ${(m.rawBytes / 1024).toFixed(1)} KB)`);
console.log(`total ${(total / 1024).toFixed(1)} KB (raw ${(rawTotal / 1024).toFixed(1)} KB)`);
